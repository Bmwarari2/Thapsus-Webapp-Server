// scripts/gen-templates.mjs — regenerate sentdm-templates.json.
//
// utils/waTemplateVars.js is the contract: it is what the sender fills at
// runtime and what the unit tests pin. The JSON manifest is only ever a
// paste-sheet for the sent.dm console, and when the two were maintained
// by hand they drifted — the manifest still carried named {{placeholders}}
// and a welcome body that asked for the customer's name, which the
// info-first rewrite had already removed. Registering from that sheet
// would have got the wrong copy approved.
//
// Run: node scripts/gen-templates.mjs
import fs from 'node:fs';
import { TEMPLATE_SLOTS } from '../utils/waTemplateVars.js';

// One realistic sample per field, in the shape Meta wants for review.
const SAMPLE = {
  full_name: 'Martha',
  order_ref: 'TRK-8823',
  total_kes: '6,486',
  expires_at: '25 August',
  tracking_code: 'TRK-8829',
  fee_kes: '300',
  receipt_token: 'TRK-8829.vtDo2gQ',
};

const templates = Object.entries(TEMPLATE_SLOTS).map(([key, slot]) => ({
  name: `tc_${key}`,
  key,
  channel: 'whatsapp',
  language: 'en',
  category: 'UTILITY',
  body: {
    template: slot.body,
    samples: slot.vars.map((v) => SAMPLE[v] ?? v),
  },
}));

const out = {
  _readme:
    'GENERATED by scripts/gen-templates.mjs from utils/waTemplateVars.js — edit that, not this. '
    + 'Create these in the sent.dm console (channel: whatsapp, language: en, category: UTILITY). '
    + 'Variables are POSITIONAL ({{1}}, {{2}}, … in body order), which sent.dm sends as var_1..var_N. '
    + 'Two rules Meta enforces: a body may not end in a variable, and a variable should not be an '
    + 'entire URL — which is why the receipt body writes the domain itself and takes only the token. '
    + 'After approval, map key → name in /ops/settings → "sent.dm template map".',
  _not_required:
    'welcome, welcome_media, onboarded and payment_verifying are deliberately absent. Each one only '
    + 'ever fires as a direct reply to an inbound message, so the 24-hour customer-service window is '
    + 'always open and free text always gets through. A template buys nothing there.',
  _template_map_after_approval: Object.fromEntries(
    Object.keys(TEMPLATE_SLOTS).map((k) => [k, `tc_${k}`])
  ),
  templates,
};

fs.writeFileSync('sentdm-templates.json', `${JSON.stringify(out, null, 2)}\n`);
console.log(`✓ wrote sentdm-templates.json — ${templates.length} templates`);
